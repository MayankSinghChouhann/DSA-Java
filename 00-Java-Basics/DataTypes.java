public class DataTypes {
    public static void main(String[] args) {
        byte b = 100;
        short s = 20000;
        int i = 1_000_000;
        long l = 9_000_000_000L;
        float f = 3.14f;
        double d = 2.718281828;
        char c = 'J';
        boolean flag = true;
        System.out.println(b + " " + s + " " + i + " " + l);
        System.out.println(f + " " + d + " " + c + " " + flag);
    }
}